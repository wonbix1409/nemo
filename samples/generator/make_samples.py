def save_docx(name, paragraphs, table=None):
    d = docx.Document()
    st = d.styles["Normal"]
    st.font.name, st.font.size = "Times New Roman", Pt(12)
    for p in paragraphs:
        d.add_paragraph(p)
    if table:
        t = d.add_table(rows=0, cols=len(table[0]))
        t.style = "Table Grid"
        for row in table:
            cells = t.add_row().cells
            for c, v in zip(cells, row):
                c.text = str(v)
    d.save(OUT / name)


