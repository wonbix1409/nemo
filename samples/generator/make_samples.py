def kpp(region="59"):
    return region + "0" + num(1) + "01001"


def phone():
    return f"+7 (9{num(2)}) {num(3)}-{num(2)}-{num(2)}"


def passport():
    return f"{num(2)} {num(2)} № {num(6)}"


